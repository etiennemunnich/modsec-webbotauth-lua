-- 6. Missing file is an error value, not a crash.
local s, err = keys.load(H.tmp("does-not-exist.tsv"))
H.eq(s, nil)
H.eq(err:match("^key store not readable") ~= nil, true)
H.pass("missing store returns nil + reason")

-- 7. A lookup parses only the lines it needs (the store is read again for
-- every ModSecurity run): by identifier, or by keyid for a url-less
-- signature. Matches are exact, and every kept line is checked as in a full
-- parse; a bad line for another agent does not affect this one.
local fixture = H.read(H.here .. "fixtures/wba-keys.tsv")
local only = assert(keys.parse(fixture, { identifier = ID }))
H.eq(only[ID][KID].proof, "valid", "the wanted identifier's keys")
H.eq(only[B_ID], nil, "another identifier's keys are not parsed")
local by_kid = assert(keys.parse(fixture, { keyid = KID }))
H.eq(by_kid[ID][KID] ~= nil and by_kid[V6_ID][KID] ~= nil, true, "url-less: the keyid under every identifier")
H.eq(by_kid[B_ID], nil, "url-less: other keyids are not parsed")
local bad_other = fixture .. "https://zzz.example/.well-known/http-message-signatures-directory\tnot-a-keyid\n"
H.eq(keys.parse(bad_other), nil, "a full parse still rejects a malformed line")
H.eq(assert(keys.parse(bad_other, { identifier = ID }))[ID][KID] ~= nil, true, "another agent's bad line does not fail this lookup")
local bad_mine = fixture .. ID .. "\tnot-a-keyid\n"
H.eq(keys.parse(bad_mine, { identifier = ID }), nil, "a malformed line for the wanted agent fails the lookup")
H.eq(next(assert(keys.parse(fixture, { identifier = ID:sub(1, -2) }))), nil, "a prefix of an identifier matches nothing")
H.eq(next(assert(keys.parse(fixture, { keyid = "-" }))), nil, "a keyid matches the keyid field only, not another field")
H.eq(next(assert(keys.parse(fixture, { keyid = KID:sub(1, 42) }))), nil, "a prefix of a keyid matches nothing")
H.eq(keys.parse("# not a store\n" .. ID .. "\t" .. KID, { identifier = ID }), nil, "the header is still required")
H.pass("a lookup parses only its identifier's or keyid's lines, exactly, each checked in full")

-- 8. One request's lookups share an index from the second one on: the same
-- lines as the finds, and one pass over the store instead of one per lookup
-- (a request with many signatures naming different keys; security review).
local function dump(s, err)
    if not s then return "nil:" .. tostring(err) end
    local out = {}
    for id, ks in pairs(s) do
        for kid, k in pairs(ks) do
            out[#out + 1] = table.concat({ id, kid, k.type, tostring(k.alg), H.hex(k.key or k.n or ""), tostring(k.nbf), tostring(k.exp), tostring(k.proof) }, "|")
        end
    end
    table.sort(out)
    return table.concat(out, "\n")
end
for _, text in ipairs({ fixture, bad_other, bad_mine, (fixture:gsub("\n", "\r\n")) }) do
    local wants = { { identifier = ID }, { identifier = B_ID }, { identifier = V6_ID }, { keyid = KID }, { keyid = "-" },
        { identifier = ID:sub(1, -2) }, { keyid = KID:sub(1, 42) }, { identifier = "https://zzz.example/.well-known/http-message-signatures-directory" },
        { keyid = "not-a-keyid" } }
    local index = {}
    for _, w in ipairs(wants) do
        H.eq(dump(keys.parse(text, w, index)), dump(keys.parse(text, w)), "indexed lookup " .. (w.identifier or w.keyid))
    end
    H.eq(index.by_id ~= nil, true, "the index was built")
end
local big = { keys.HEADER }
local line1 = fixture:match("\n(" .. ID:gsub("%p", "%%%0") .. "\t[^\n]*)")
for i = 1, 3000 do big[#big + 1] = (line1:gsub("^https://", "https://a" .. i .. ".")) end
big = table.concat(big, "\n") .. "\n"
local function lookups(index)
    return H.searches(big, function()
        for i = 1, 150 do assert(keys.parse(big, { keyid = ("k%042d"):format(i) }, index)) end
    end)
end
local plain, indexed = lookups(nil), lookups({})
H.eq(plain, 150, "without an index: one search of the store per lookup")
H.eq(indexed <= 2, true, ("with one index: the store searched %d times for 150 lookups, not once each"):format(indexed))
H.pass(("lookups share one index per request: the same lines; 150 lookups in 3000 lines search the store %d times, not 150"):format(indexed))

H.done("test_keys")
