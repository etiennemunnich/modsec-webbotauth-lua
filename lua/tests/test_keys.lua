H.eq(s1[ID][KID].type, "ed25519")
H.eq(s1[ID][KID].alg, nil)
H.eq(s1[ID][KID].key, RAW)
H.eq(s1[ID][KID].exp, 5)
H.eq(s1[ID][KID].proof, "none", "no proof columns: proof none")
