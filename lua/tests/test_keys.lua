-- test_keys.lua: the key-store contract (the file wba-keysync writes) and
-- the identifier rules (identifier.lua) it is keyed on.
-- Run: lua lua/tests/test_keys.lua
package.path = ((arg[0]:match("(.*/)") or "./") .. "?.lua;") .. package.path
local H = require("helpers")
local keys = require("wba.keys")

local b64 = require("wba.base64")

local ID = "https://agent.example/.well-known/http-message-signatures-directory"
local B_ID = "https://b.example:8443/.well-known/http-message-signatures-directory"
local V6_ID = "https://[2001:db8::1]:8443/jwks.json"
-- A key generated for these fixtures (private half discarded), and its RFC
-- 7638 thumbprint computed by openssl. RFC 8037's key cannot serve: its
-- private half is published, so it is on the test-key list.
local KID = "YIGq9u-ucksC9KcownKqCEJ082n_7gSkCozYsYaS7y8"
local RAW = b64.decode((("zxCdg3SebLwIqmV8uI0V-H-jFYwleEZGPFRlD98KVKc"):gsub("%-", "+"):gsub("_", "/")) .. "=")
local HEX = H.hex(RAW)

-- 1. The shared fixture: wba-keysync's test suite asserts it emits these
-- exact bytes. It holds every key type and every proof state.
local store = assert(keys.load(H.here .. "fixtures/wba-keys.tsv"))
local e = store[ID][KID]
H.eq(e.type, "ed25519")
H.eq(e.alg, nil, "alg '-' is no alg")
H.eq(e.key, RAW, "hex decodes to the raw fixture key")
H.eq(e.nbf, 1712793600)
H.eq(e.exp, 1715385600)
H.eq(e.proof, "valid")
H.eq(e.proof_exp, 1715000000)
local other = store[B_ID][H.RFC_KEYID]
H.eq(other.key, H.RFC_KEY_RAW, "second identifier, non-default port, RFC 9421 key")
H.eq(other.alg, "ed25519")
H.eq(other.nbf, nil)
H.eq(other.exp, nil)
H.eq(other.proof, "none")
H.eq(other.proof_exp, nil)
H.eq(store[V6_ID][KID].proof, "invalid", "a jwks_uri identifier on an IPv6 literal")
-- The EC and RSA fixture keys were generated by openssl for these fixtures
-- (private halves discarded); each keyid is its RFC 7638 thumbprint, which
-- openssl recomputes here from the parsed key.
local p256 = store[ID]["k_68AQ2ZHOzotenLHvB06vit-mGArdHu98aNlur-mbY"]
H.eq(p256.type, "ec-p256")
H.eq(p256.alg, "ecdsa-p256-sha256")
H.eq(#p256.key, 65)
H.eq(p256.proof, "none")
H.eq(H.entry_thumbprint(p256), "k_68AQ2ZHOzotenLHvB06vit-mGArdHu98aNlur-mbY", "P-256 thumbprint (RFC 7638 3.2)")
local rsa = store[B_ID]["SWbXVsyNhvdYgDdwSXlQMoeKmiEBegGW0OaFmYHIwEw"]
H.eq(rsa.type, "rsa")
H.eq(rsa.alg, "rsa-pss-sha512")
H.eq(#rsa.n, 256, "2048-bit modulus, minimal")
H.eq(rsa.e, "\1\0\1")
H.eq(rsa.exp, 1800000000)
H.eq(rsa.proof, "invalid")
H.eq(H.entry_thumbprint(rsa), "SWbXVsyNhvdYgDdwSXlQMoeKmiEBegGW0OaFmYHIwEw", "RSA thumbprint (RFC 7638 3.2)")
local p384 = store["https://c.example/.well-known/http-message-signatures-directory"]["Xs8ArbSNwEeH7d1mn0Lmfqeu-e4uuvg5yL1tLnilhWY"]
H.eq(p384.type, "ec-p384")
H.eq(#p384.key, 97)
H.eq(p384.proof, "valid")
H.eq(p384.proof_exp, 1716000000)
H.eq(H.entry_thumbprint(p384), "Xs8ArbSNwEeH7d1mn0Lmfqeu-e4uuvg5yL1tLnilhWY", "P-384 thumbprint")
H.pass("shared fixture (the file wba-keysync emits) parses: Ed25519, P-256, P-384 and RSA keys, alg pins, identifiers, nbf/exp, every proof state; keyids are their thumbprints")

-- 2. Identifiers: every row of the vectors identifier.ts also runs.
local WK = keys.WELL_KNOWN
local rows = 0
for line in io.lines(H.here .. "fixtures/identifiers.tsv") do
    if line ~= "" and line:sub(1, 1) ~= "#" and not line:match("^mode\t") then
        local mode, input, want = line:match("^([^\t]+)\t([^\t]*)\t([^\t]+)$")
        assert(mode, "malformed vector line: " .. line)
        want = want:gsub("WK$", WK)
        if want == "-" then want = nil end
        local got
        if mode == "origin" then got = keys.identifier(input, true)
        elseif mode == "lenient" then got = keys.identifier(input)
        elseif mode == "url" then got = keys.url_identifier(input)
        else error("unknown mode " .. mode) end
        H.eq(got, want, mode .. " " .. input)
        if got then H.eq(keys.valid_identifier(got), true, "an identifier is its own normal form: " .. got) end
        rows = rows + 1
    end
end
H.eq(rows >= 100, true, "vectors read")
H.eq(keys.identifier(""), nil)
H.eq(keys.url_identifier(""), nil)
H.pass(rows .. " identifier vectors: directory origins (strict and lenient), jwks_uri/cimd URLs, IPv6 literals (RFC 5952)")

-- 3. Anything malformed rejects the whole file.
local function row(t, alg, key, id, proof)
    return table.concat({ id or ID, KID, t, alg or "-", key, "-", "-", proof or "none\t-" }, "\t")
end
local function v2(...) return keys.HEADER .. "\n" .. row(...) .. "\n" end
local line = row("ed25519", nil, HEX)
H.eq(keys.parse(v2("ed25519", nil, HEX)) ~= nil, true, "minimal valid store")
H.eq(keys.parse((v2("ed25519", nil, HEX):gsub("\n", "\r\n"))) ~= nil, true, "CRLF tolerated")
H.eq(keys.parse(keys.HEADER .. "\n" .. line .. "\r") ~= nil, true, "final CR without LF (same rule as keysync parse)")
H.eq(assert(keys.parse(v2("ed25519", nil, HEX, nil, "valid\t1715000000")))[ID][KID].proof_exp, 1715000000)
H.eq(assert(keys.parse(v2("ed25519", nil, HEX, V6_ID, "invalid\t-")))[V6_ID][KID].proof, "invalid")
local v1line = ID .. "\t" .. KID .. "\t" .. HEX .. "\t-\t-"
local P256 = H.hex(p256.key)
local RSA = H.hex(rsa.n) .. ":010001"
local bad_files = {
    { line, "missing header" },
    { "# wba-keys v3\n" .. line, "unknown version" },
    { v2("ed25519", nil, HEX) .. line, "duplicate key" },
    { keys.HEADER .. "\n" .. v1line, "a version 1 line under the version 2 header" },
    { keys.HEADER_V1 .. "\n" .. line, "a version 2 line under the version 1 header" },
    { keys.HEADER .. "\n" .. table.concat({ ID, KID, "ed25519", "-", HEX, "-", "-" }, "\t"), "7 fields (no proof columns)" },
    { v2("ed25519", nil, HEX:sub(3)), "short key" },
    { v2("ed25519", nil, HEX:upper()), "uppercase hex" },
    { keys.HEADER .. "\n" .. line:gsub(KID:gsub("%p", "%%%0"), KID:sub(2)), "short keyid" },
    { v2("ed25519", nil, HEX, (ID:gsub("^https://agent.example", "https://agent.example:443"))), "non-canonical identifier" },
    { v2("ed25519", nil, HEX, (ID:gsub("^https://agent.example", "https://Agent.example"))), "uppercase identifier" },
    { v2("ed25519", nil, HEX, "https://a.example/jwks.json?v=1"), "identifier with a query" },
    { v2("ed25519", nil, HEX, "https://[2001:db8:0::1]/k"), "IPv6 identifier not in RFC 5952 form" },
    { keys.HEADER .. "\n" .. line:gsub("\t%-\t%-\tnone", "\tsoon\t-\tnone"), "bad nbf" },
    { v2("ed25519", nil, HEX, nil, "yes\t-"), "unknown proof status" },
    { v2("ed25519", nil, HEX, nil, "valid\t-"), "valid proof without its expires" },
    { v2("ed25519", nil, HEX, nil, "none\t5"), "an expires on a proof that is not valid" },
    { v2("ed25519", nil, HEX, nil, "invalid\t5"), "an expires on an invalid proof" },
    { v2("x25519", nil, HEX), "unknown key type" },
    { v2("ed25519", "EdDSA", HEX), "a JOSE alg name (draft 5.5.1: the HTTP Signature Algorithms registry)" },
    { v2("ed25519", "hmac-sha256", HEX), "hmac-sha256 (draft 6.4)" },
    { v2("ec-p256", "ecdsa-p384-sha384", P256), "alg for another key type" },
    { v2("rsa", "ed25519", RSA), "an Ed25519 alg on an RSA key" },
    { v2("ec-p384", nil, P256), "a P-256 point typed as P-384" },
    { v2("ec-p256", nil, "02" .. P256:sub(3, 66)), "a compressed point (RFC 7518 6.2.1: no compression)" },
    { v2("ec-p256", nil, "05" .. P256:sub(3)), "not an uncompressed point" },
    { v2("rsa", nil, "00" .. RSA), "RSA n with a leading zero byte (RFC 7518 2: minimal)" },
    { v2("rsa", nil, H.hex(rsa.n):sub(2) .. ":010001"), "RSA n of odd hex length" },
    { v2("rsa", nil, H.hex(rsa.n):sub(1, -2) .. "e:010001"), "an even RSA modulus (RFC 8017 3.1)" },
    { v2("rsa", nil, H.hex(rsa.n) .. ":01"), "e = 1 (RFC 8017 3.1: 3 <= e)" },
    { v2("rsa", nil, H.hex(rsa.n) .. ":010000"), "an even e" },
    { v2("rsa", nil, H.hex(rsa.n) .. ":0003"), "e with a leading zero byte" },
    { v2("rsa", nil, H.hex(rsa.n) .. ":01" .. ("00"):rep(31) .. "01"), "e of 257 bits" },
    { v2("rsa", nil, "8" .. ("0"):rep(4096) .. "1:010001"), "a 16392-bit modulus (over 16384)" },
    { v2("rsa", nil, H.hex(rsa.n)), "RSA without e" },
    { "", "empty file" },
}
for _, b in ipairs(bad_files) do
    local s, err = keys.parse(b[1])
    H.eq(s, nil, "must reject: " .. b[2])
    H.eq(type(err), "string")
end
H.pass("rejects " .. #bad_files .. " malformed stores (header, duplicates, identifiers, proofs, key types, alg pins, EC points, RSA n and e)")

-- 4. RSA key size and exponent bounds (algorithms.lua): keys openssl makes,
-- either side of the 2048-bit floor, and the edges of what is accepted.
local small = H.new_key("rsa", 2047)
H.eq(#small.entry.n, 256, "a 2047-bit modulus still takes 256 bytes")
H.eq(keys.parse(v2("rsa", nil, H.hex(small.entry.n) .. ":010001")), nil,
    "2047 bits: refused (RFC 7518 3.3, 3.5: 2048 bits or larger)")
local tiny = H.new_key("rsa", 1024)
H.eq(keys.parse(v2("rsa", nil, H.hex(tiny.entry.n) .. ":010001")), nil, "1024 bits: refused")
H.eq(keys.parse(v2("rsa", nil, RSA)) ~= nil, true, "2048 bits: accepted")
H.eq(keys.parse(v2("rsa", nil, H.hex(rsa.n) .. ":03")) ~= nil, true, "e = 3 (RFC 8017 3.1)")
H.eq(keys.parse(v2("rsa", nil, H.hex(rsa.n) .. ":" .. ("f"):rep(64))) ~= nil, true, "a 256-bit e")
H.eq(keys.parse(v2("rsa", nil, "8" .. ("0"):rep(4094) .. "1:010001")) ~= nil, true, "a 16384-bit modulus")
H.eq(keys.parse(v2("rsa", nil, "8" .. ("0"):rep(1022) .. "1:01" .. ("0"):rep(14) .. "01")), nil,
    "4096 bits with a 65-bit e: refused (OpenSSL verifies none)")
H.eq(keys.parse(v2("rsa", nil, "8" .. ("0"):rep(766) .. "1:01" .. ("0"):rep(14) .. "01")) ~= nil, true, "3072 bits with a 65-bit e")
H.eq(keys.parse(v2("rsa", nil, "8" .. ("0"):rep(1022) .. "1:" .. ("f"):rep(16))) ~= nil, true, "4096 bits with a 64-bit e")
H.pass("RSA: 2047-bit and 1024-bit openssl keys refused, 2048 to 16384 bits accepted; e odd, 3 to 2^256 - 1")

