-- Content codings (Unencoded-Digest, decoded by coding.lua) and partial PUT
-- (RFC 9110 14.4, 14.5). Octet-stream keeps ModSecurity's body processors
-- off the coded bytes.
local function gzip(s)
    local i, g = H.tmp("gzip.in"), H.tmp("gzip.out")
    H.write(i, s)
    assert(H.sh(("gzip -c -n '%s' > '%s'"):format(i, g)))
    return H.read(g)
end
