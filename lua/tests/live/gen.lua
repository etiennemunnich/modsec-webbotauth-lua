-- o.alg: the alg parameter (default: the key type's own; false: omitted);
-- o.sign_alg: what openssl signs with (default: o.alg, else the key type's);
-- o.der: ECDSA as DER, not r || s; o.member: the Signature-Agent member,
-- under key o.agent_key (default agent1); o.nonce: the nonce parameter;
-- o.params: the whole parameter string instead; o.keyid: another keyid;
-- o.agent_header: the Signature-Agent header value as written.
-- Response headers go to OUT/<case>.hdr.
local function case(name, o)
    if only and only ~= name then return end
    local key = o.key or KEY
    local alg = o.alg
    if alg == nil then alg = H.DEFAULT_ALG[key.type] end
    local member = o.member or ('"' .. H.AGENT .. '"')
    local comps = o.components or '"@authority" "signature-agent";key="agent1"'
    local lines = o.lines or { '"@authority": example.com', '"signature-agent";key="agent1": ' .. member }
    local params = o.params or ((';created=%d;expires=%d;keyid="%s"'):format(o.created or now - 5, o.expires or now + 600, o.keyid or key.keyid)
        .. (alg and (';alg="%s"'):format(alg) or "") .. (o.nonce and (';nonce="%s"'):format(o.nonce) or "")
        .. ';tag="web-bot-auth"')
    local base = table.concat(lines, "\n") .. '\n"@signature-params": (' .. comps .. ")" .. params
    local hdrs = o.raw_headers or {
        "Host: " .. (o.host or "example.com"),
        "Signature-Agent: " .. (o.agent_header or ((o.agent_key or "agent1") .. "=" .. member)),
        "Signature-Input: sig1=(" .. comps .. ")" .. params,
        "Signature: sig1=:" .. b64.encode(H.sign(key, base, o.sign_alg or alg or nil, { der = o.der })) .. ":",
    }
    if o.unsigned then hdrs = { "Host: example.com" } end
    if o.raw_headers_without_agent then table.remove(hdrs, 2) end -- drop Signature-Agent
    if os.getenv("PRINT") then
        for _, h in ipairs(hdrs) do print(h) end
        for _, h in ipairs(o.extra or {}) do print(h) end
        -- For h2.ts: the request's pseudo-headers (lines starting ":" are not
        -- header lines to the scripts that grep for "Name: value").
        print(":method: " .. (o.method or "GET"))
        print(":path: " .. (o.path or "/"))
        return
    end
    local cmd = "curl -s -o /dev/null -D '" .. OUT .. "/" .. name .. ".hdr' --max-time 5 --path-as-is -w '%{http_code} %{http_version}' -H 'X-WBA-Test: " .. name .. "'"
    if o.target then cmd = cmd .. " --request-target '" .. o.target .. "'" end
    if o.method then cmd = cmd .. " -X '" .. o.method .. "'" end
    -- TLS by default, like a real site;
    -- o.h2 negotiates HTTP/2 (curl sends Host as :authority); o.cleartext
    -- uses the plain port.
    if o.h2 then cmd = cmd .. " --http2 -k" elseif not o.cleartext then cmd = cmd .. " --http1.1 -k" end
    if o.body then
        local bf = H.tmp("body-" .. name)
        H.write(bf, o.body)
        cmd = cmd .. " --data-binary @'" .. bf .. "' -H 'Content-Type: " .. (o.ctype or "application/json") .. "'"
    end
    for _, h in ipairs(hdrs) do cmd = cmd .. " -H '" .. h .. "'" end
    for _, h in ipairs(o.extra or {}) do cmd = cmd .. " -H '" .. h .. "'" end
    local url = o.cleartext and ("http://127.0.0.1:" .. port)
        or os.getenv("BASE_URL") or ("https://127.0.0.1:" .. (os.getenv("TLS_PORT") or "8443"))
    local p = io.popen(cmd .. " '" .. url .. (o.path or "/") .. "'")
    local code = p:read("a")
    p:close()
    -- "<case> <HTTP status> <HTTP version>": run.sh reads the status the case
    -- got, and the version to prove a case went over HTTP/2.
    print(name .. " " .. code)
end

