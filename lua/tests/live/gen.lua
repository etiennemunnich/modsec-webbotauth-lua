-- RFC 9530 and draft-ietf-httpbis-unencoded-digest-05: signatures over a
-- digest field, decided in phase 2. openssl computes every digest,
-- independently of sha256.lua; the gzip CLI encodes.
local function b64digest(alg, body)
    local f = H.tmp("digest.in")
    H.write(f, body)
    local p = io.popen(("openssl dgst -%s -binary '%s' | openssl base64 -A"):format(alg, f))
    local d = p:read("a")
    p:close()
    return d
end
local FIELD = { ["content-digest"] = "Content-Digest", ["repr-digest"] = "Repr-Digest",
                ["unencoded-digest"] = "Unencoded-Digest" }
-- o.value (the digest field value as written), o.field (default content-digest), o.digest_of (default o.body), o.sent
-- (the body sent instead), o.method, o.extra headers, o.key (the signing key), o.path.
local function body_case(name, o)
    if only and only ~= name then return end
    local alg, field = o.alg or "sha256", o.field or "content-digest"
    local v = o.value or ("%s=:%s:"):format(alg == "sha512" and "sha-512" or "sha-256", b64digest(alg, o.digest_of or o.body))
    local extra = { FIELD[field] .. ": " .. v }
    for _, h in ipairs(o.extra or {}) do extra[#extra + 1] = h end
    case(name, { body = o.sent or o.body, h2 = o.h2, extra = extra, ctype = o.ctype, method = o.method, key = o.key, path = o.path,
        components = '"@authority" "' .. field .. '" "signature-agent";key="agent1"',
        lines = { '"@authority": example.com', '"' .. field .. '": ' .. v, AGENT_LINE } })
end
