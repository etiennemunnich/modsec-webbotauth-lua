-- gen.lua: signs live test requests for run.sh. openssl signs over
-- hand-written RFC 9421 bases; curl sends them.
--   MODE=keys  OUT=<dir>              write <dir>/keys/wba-keys.tsv (format v2: every key but key 2)
--   MODE=send  OUT=<dir> PORT=<port> TLS_PORT=<port>  send every case (or only CASE=<name>)
--   PRINT=1 with MODE=send: print the headers of CASE instead of sending, then
--            its :method and :path (h2.ts sends those over HTTP/2)
--   BASE_URL=https://example.com with MODE=send: send TLS cases there instead
--            of 127.0.0.1, so the server sees the name in the TLS handshake
